import assert from "node:assert/strict";
import {getGuidedTest,renderGuidedTestMarkup} from "../js/guided-test-library.js";
const network=getGuidedTest({id:"resistance"},"j1939_network");
assert.match(network.objective,/de-energized topology/i);
assert.ok(network.stop.some(x=>/energized network/i.test(x)));
const oldId=getGuidedTest({id:"resistance"},"j1939_dropout");
assert.equal(oldId.objective,network.objective);
const general=getGuidedTest({id:"drop"},"general_electrical");
assert.match(general.objective,/positive-feed loss/i);
const battery=getGuidedTest({id:"battery_baseline"},"power_loss");
assert.match(battery.where,/lead battery posts, not cable clamps/i);
const fuel=getGuidedTest({id:"fuel"},"crank_no_start");
assert.match(fuel.where,/OEM-designated low-pressure test port/i);
assert.ok(fuel.stop.some(x=>/high-pressure fuel lines/i.test(x)));
const unknown=getGuidedTest({id:"unknown",title:"Unknown test"},"unknown");
assert.ok(unknown.stop.some(x=>/stop before probing/i.test(x)));
assert.doesNotMatch(JSON.stringify(unknown),/pin\s*[0-9]+|\b\d+(?:\.\d+)?\s*(?:psi|volts?|ohms?)\b/i);
const mackFuel=getGuidedTest({id:"fault_test",title:"Evaluate low-pressure fuel supply using the Mack-specific procedure"},"fault_guidance_p008a00_0");
assert.match(mackFuel.where,/Mack\/engine service procedure/i);
assert.ok(mackFuel.stop.some(x=>/high-pressure fuel lines/i.test(x)));
const mackBranch=getGuidedTest({id:"fault_isolate",title:"Separate a supply problem from a control or sensor-circuit problem"},"fault_guidance_p008a00_0");
assert.match(mackBranch.objective,/scan-data, sensor-circuit or control discrepancy/i);
const html=renderGuidedTestMarkup({id:"load"},"light_inop");
assert.match(html,/GUIDED TEST PLAN/);
assert.match(html,/Where to test/);
assert.match(html,/Stop \/ safety checks/);
const hostile=renderGuidedTestMarkup({id:"x",title:"<img src=x>",test:"<script>bad</script>"},"unknown");
assert.doesNotMatch(hostile,/<img|<script>/);
assert.match(hostile,/&lt;script&gt;/);
console.log("Guided test library tests passed.");
